/* Classement local des vidéos : c'est ici qu'on « dirige l'algo ».
 * On ne change pas l'algorithme de X : on réordonne ce qu'il nous donne, on filtre, et on construit des recherches. */
(() => {
  'use strict';
  const NCT = (globalThis.NCT = globalThis.NCT || {});
  const T = NCT.themes;

  const HARD_BLOCK = 0.03; // une cible à 3 % ou moins exclut le thème

  // Part des 200 dernières vidéos vues qui touchent chaque thème.
  function measured(views) {
    const recent = (views || []).slice(-200);
    const total = recent.length;
    const shares = {};
    for (const t of T.THEMES) shares[t.id] = 0;
    for (const v of recent) for (const id of v.themes || []) if (id in shares) shares[id]++;
    if (total) for (const id in shares) shares[id] /= total;
    return { total, shares };
  }

  function hasWord(norm, word) {
    const n = T.norm(word);
    return n.trim() !== '' && norm.includes(n);
  }

  // Marqueurs de contenu généré par IA (texte normalisé : minuscules, sans accents).
  // Détection par libellés X, hashtags et noms d'outils : elle ne peut pas attraper une vidéo IA non déclarée.
  const AI_RE = new RegExp(
    '(^| )(' + [
      'aigc', 'aiart', 'aivideo', 'aigenerated', 'iagenerative', 'genai',
      'ai generated', 'ai generee?', 'made with ai', 'created with ai', 'generated by ai', 'generated with ai', 'ai video', 'ai art',
      'ai[- ]?slop', 'genere(e)? (par|avec|grace a) (l )?ia', 'cree(e)? (par|avec) (l )?ia', 'video ia', 'video generee', 'contenu genere',
      'sora 2', 'sora ai', 'openai sora', 'veo 3', 'veo3', 'google veo', 'kling ai', 'kling 2', 'runway gen', 'runway ml', 'midjourney',
      'higgsfield', 'seedance', 'hailuo', 'minimax video', 'pika labs', 'luma dream machine', 'grok imagine', 'made with grok', 'stable diffusion',
      'comfyui', 'text to video', 'image to video', 'heygen', 'deepfake', 'synthetic media', 'nano banana'
    ].join('|') + ')( |$)'
  );
  // Hashtags explicites uniquement : un simple « IA » ou « AI » dans un texte parle souvent de l'IA sans être une vidéo générée.
  const AI_TAG = /#(aiart|aivideo|aigenerated|aigc|genai|iagenerative|sora2?|veo3?|midjourney|klingai|aislop)(?![\p{L}\p{N}])/iu;
  const isAI = (item) => !!(item.ai || AI_RE.test(item.norm || '') || AI_TAG.test((item.text || '') + ' ' + (item.name || '')));

  // Une vidéo « correspond » à la zone ciblée si un lieu de cette zone est cité ; pour la France, une langue « fr » sans autre lieu compte aussi.
  function inRegion(item, st) {
    const sel = st.regions || [];
    if (!sel.length) return null;
    const rs = item.regions || [];
    return rs.some((r) => sel.includes(r)) || (sel.includes('france') && !rs.length && /^fr(-|$)/i.test(item.lang || ''));
  }

  // Pourquoi une vidéo est écartée (null = elle passe). Les clés servent aussi au schéma « entonnoir » de l'interface.
  function reason(item, st) {
    if (st.blockAI && isAI(item)) return 'ai';
    if ((st.hiddenAccounts || []).includes(item.handle.toLowerCase())) return 'account';
    const reg = inRegion(item, st);
    if (reg !== null) {
      const mode = st.regionMode || 'prefer';
      if (mode === 'exclude' && reg) return 'region';
      if (mode === 'only' && !reg && !(st.regionKeepUnknown && !(item.regions || []).length)) return 'region';
    }
    for (const w of st.blockWords || []) if (hasWord(item.norm, w)) return 'word';
    if (st.noViolence && (item.sensitive || (item.themes || []).includes('violence'))) return 'violence';
    for (const id of item.themes) {
      const t = st.targets && st.targets[id];
      if (typeof t === 'number' && t <= HARD_BLOCK) return 'theme';
    }
    const langs = st.languages || [];
    const m = /^([a-z]{2})(?:-|$)/i.exec(item.lang || ''); // seulement les vrais codes à 2 lettres ; « und », « qme », « zxx »… passent
    if (langs.length && m && !langs.includes(m[1].toLowerCase())) return 'lang';
    return null;
  }
  const excluded = (item, st) => reason(item, st) !== null;

  /* ---- Mélange voulu (tableau de bord de l'algo) ----
   * Les cibles réglées (ex. Jeux vidéo 100 %, Actu 60 %) deviennent des parts du flux, ramenées à 80 % au total pour
   * toujours laisser au moins 20 % au fil de X lui-même (ici 50 % jeux, 30 % actu, 20 % Pour vous).
   * Elles se comparent aux dernières vidéos réellement lues dans Nocturne. */
  const MIX_MAX = 0.8;
  function wanted(targets) {
    const t = Object.entries(targets || {}).filter(([id, v]) => typeof v === 'number' && v > HARD_BLOCK && id !== 'violence');
    const sum = t.reduce((a, [, v]) => a + v, 0);
    const k = sum > MIX_MAX ? MIX_MAX / sum : 1;
    return Object.fromEntries(t.map(([id, v]) => [id, v * k]));
  }
  // Part de chaque thème dans les dernières vidéos lues (log : une liste de thèmes par vidéo).
  function mixShares(log, n = 12) {
    const recent = (log || []).slice(-n);
    const out = {};
    for (const th of recent) for (const id of th || []) out[id] = (out[id] || 0) + 1;
    for (const id in out) out[id] /= recent.length || 1;
    return out;
  }
  // Le thème qui manque le plus (écart entre la part voulue et la part lue), s'il manque d'au moins minGap.
  function lacking(targets, log, minGap = 0.12) {
    const w = wanted(targets);
    const sh = mixShares(log);
    let best = null;
    for (const id of Object.keys(w)) {
      const gap = w[id] - (sh[id] || 0);
      if (gap >= minGap && (!best || gap > best.gap)) best = { id, gap, want: w[id], share: sh[id] || 0 };
    }
    return best;
  }

  function score(item, ctx) {
    const st = ctx.settings;
    const fb = ctx.feedback || { handles: {}, words: {}, themes: {} };
    let s = 0;
    for (const id of item.themes) {
      const target = ctx.wanted ? ctx.wanted[id] : st.targets && st.targets[id];
      const m = (ctx.shares && ctx.shares[id]) || 0;
      if (typeof target === 'number') s += (target - m) * 3;
      s += (fb.themes[id] || 0) * 0.5;
    }
    for (const w of st.favWords || []) if (hasWord(item.norm, w)) s += 2;
    if (inRegion(item, st) && (st.regionMode || 'prefer') === 'prefer') s += 2.5;
    s += fb.handles[item.handle.toLowerCase()] || 0;
    for (const w of item.words) s += (fb.words[w] || 0) * 0.4;
    return s;
  }

  // Verdict automatique d'un tweet d'après ses chiffres (affiché sous la vidéo) : 0 discret, 1 moyen, 2 marche bien, 3 carton.
  // Tient compte des vues, du taux d'interactions (j'aime + reposts + réponses ÷ vues) et de la vitesse (vues par heure).
  const LEVELS = ['Discret', 'Moyen', 'Marche bien', 'Carton'];
  function verdict(m, postedAt, now = Date.now()) {
    if (!m) return null;
    const v = m.views, l = m.likes || 0, r = m.reposts || 0, c = m.replies || 0;
    const ageH = postedAt ? Math.max(1, (now - Date.parse(postedAt)) / 3600000) : null;
    let pts;
    if (v != null && v > 0) {
      const eng = (l + r + c) / v;
      pts = v >= 1e6 ? 4 : v >= 1e5 ? 3 : v >= 1e4 ? 2 : v >= 1e3 ? 1 : 0;
      if (v >= 500) pts += eng >= 0.06 ? 2 : eng >= 0.03 ? 1 : 0;
      if (ageH && v / ageH >= 1e4) pts += 1;
      const level = pts >= 5 ? 3 : pts >= 3 ? 2 : pts >= 1 ? 1 : 0;
      return { level, label: LEVELS[level], eng, ageH };
    }
    if (!l && !r) return null;
    const level = l >= 1e4 ? 3 : l >= 1e3 ? 2 : l >= 100 ? 1 : 0;
    return { level, label: LEVELS[level], eng: null, ageH };
  }

  // Choisit la prochaine vidéo parmi une fenêtre de candidates.
  function pick(cands, ctx, rnd = Math.random) {
    if (!cands.length) return null;
    if (rnd() * 100 < (ctx.settings.discover || 0)) return cands[Math.floor(rnd() * cands.length)];
    let best = cands[0];
    let bs = score(best, ctx);
    for (let i = 1; i < cands.length; i++) {
      const sc = score(cands[i], ctx);
      if (sc > bs + 1e-9) { best = cands[i]; bs = sc; }
    }
    return best;
  }

  const quote = (t) => (/\s/.test(t) ? '"' + t.replace(/"/g, '') + '"' : t);

  // Requête X : exactement ce que tu as tapé (un seul sujet) ; plusieurs sujets sont réunis avec OR.
  // Les filtres (langues, mots bloqués, IA, durée) sont appliqués ici, en local, pas dans la requête.
  function buildSearchQuery(topics, st, opts) {
    const ts = (topics || []).map((t) => t.trim()).filter(Boolean);
    let q = ts.length === 1 ? ts[0] : ts.length > 1 ? '(' + ts.map(quote).join(' OR ') + ')' : '';
    if (!opts || opts.video !== false) q += ' filter:native_video';
    return q.trim();
  }

  const searchUrl = (q, f) => 'https://x.com/search?q=' + encodeURIComponent(q) + '&src=typed_query&f=' + (f || 'live');

  // Valeurs proposées pour la durée maximale (secondes, 0 = illimitée).
  const DURATIONS = [30, 60, 120, 180, 300, 600, 0];
  const durationLabel = (s) => (s === 0 ? 'Illimitée' : s < 60 ? s + ' s' : s / 60 + ' min');

  NCT.rank = { isAI, inRegion, HARD_BLOCK, measured, wanted, mixShares, lacking, reason, excluded, score, pick, verdict, LEVELS, buildSearchQuery, searchUrl, DURATIONS, durationLabel };
})();
